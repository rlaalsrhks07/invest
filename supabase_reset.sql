-- 현재 사이트는 별도 로그인 없이 anon key로 접근하므로 RLS를 끕니다.
-- 나누미만 주소에 접근한다는 전제의 간단한 수업용 설정입니다.
alter table public.teams disable row level security;
alter table public.rounds disable row level security;
alter table public.investments disable row level security;
alter table public.team_hint_views disable row level security;

-- anon/authenticated 역할에 필요한 권한 부여
grant select, insert, update, delete on public.teams to anon, authenticated;
grant select, insert, update, delete on public.rounds to anon, authenticated;
grant select, insert, update, delete on public.investments to anon, authenticated;
grant select, insert, update, delete on public.team_hint_views to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

commit;
